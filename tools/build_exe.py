"""Build the standalone Windows receiver executable.

Produces a Windows build that needs no Python install. The ViGEmBus *driver* is
still required on the target machine; only the Python runtime is bundled.

vgamepad loads its native client with

    Path(__file__).parent.absolute() / "vigem" / "client" / <arch> / "ViGEmClient.dll"

so that DLL has to land at vgamepad/win/vigem/client/<arch>/ViGEmClient.dll
inside the bundle. PyInstaller does not collect it on its own, hence the
explicit --add-data below.

Defaults to --onedir on purpose. A --onefile build runs a bootloader parent that
spawns the real process as a child; killing the parent (Task Manager "End task")
orphans the child, which keeps holding an open ViGEmBus handle and leaves a
phantom controller visible to every game. onedir runs as a single process and
cannot do that. It also starts faster, since nothing is re-extracted per run.

Builds the desktop app by default. --console builds the terminal receiver
instead, which is handy for debugging or running headless.

The UI is HTML rendered by the Edge WebView2 Runtime. Windows 11 always has
it and most Windows 10 PCs do, but some (LTSC, N editions, offline machines)
do not, so the installer checks for it and points to Microsoft's download; it
is not bundled. webui/ has to be shipped as data or the window comes up blank.

    python tools/build_exe.py              # desktop app     (recommended)
    python tools/build_exe.py --console    # terminal receiver
    python tools/build_exe.py --onefile    # single .exe, see caveat above

Build dependencies are pinned in pc/requirements-build.txt.

The exe carries a Windows version resource (Properties -> Details) generated
from pc/version.py, which is the only place the PC version is declared.

Code signing is opt-in and off by default, because there is no certificate
yet. Set LUDUSCTRL_SIGN_CMD to a command in which {file} stands for the quoted
path of the file to sign, e.g.

    set LUDUSCTRL_SIGN_CMD=signtool sign /fd sha256 /tr http://timestamp.digicert.com /td sha256 /a {file}

and LudusCtrl.exe is signed right after it is built. Unset, the step is
skipped with a note. tools/build_installer.py reads the same variable.
"""

from __future__ import annotations

import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PC = os.path.join(ROOT, "pc")
DIST = os.path.join(PC, "dist")
WORK = os.path.join(PC, "build")
NAME = "LudusCtrl"
PUBLISHER = "Josip Parlov"

# Front ends selectable at runtime with --ui. Both must be bundled.
# webui-mobile is the page served to a phone browser by --web; it is data
# like the other front ends, not code, so it ships the same way.
UI_FOLDERS = ("webui", "webui-instrument", "webui-mobile")

SIGN_ENV = "LUDUSCTRL_SIGN_CMD"


def app_version() -> str:
    """VERSION from pc/version.py, read as text so nothing is imported."""
    path = os.path.join(PC, "version.py")
    with open(path, encoding="utf-8") as fh:
        m = re.search(r'^VERSION\s*=\s*["\']([^"\']+)["\']', fh.read(), re.M)
    if not m:
        sys.exit("Could not read VERSION from %s" % path)
    return m.group(1)


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """"1.2" -> (1, 2, 0, 0). Windows wants exactly four 16-bit numbers."""
    parts = [int(p) for p in re.findall(r"\d+", version)[:4]]
    parts += [0] * (4 - len(parts))
    return tuple(parts)  # type: ignore[return-value]


def write_version_file(version: str, folder: str) -> str:
    """Write a PyInstaller --version-file describing this build.

    Without it the exe's Properties -> Details tab is blank, which is one of
    the things SmartScreen and antivirus heuristics count against an unsigned
    binary, and it leaves users no way to tell which build they have.
    """
    nums = version_tuple(version)
    text = f"""# Generated by tools/build_exe.py from pc/version.py. Do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={nums},
    prodvers={nums},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName', {PUBLISHER!r}),
        StringStruct('FileDescription', 'LudusCtrl receiver'),
        StringStruct('FileVersion', {version!r}),
        StringStruct('InternalName', {NAME!r}),
        StringStruct('LegalCopyright', '\\u00a9 2026 {PUBLISHER}. All rights reserved.'),
        StringStruct('OriginalFilename', {NAME + ".exe"!r}),
        StringStruct('ProductName', {NAME!r}),
        StringStruct('ProductVersion', {version!r})
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [0x0409, 1200])])
  ]
)
"""
    path = os.path.join(folder, "version_info.txt")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return path


def sign(path: str) -> int:
    """Run LUDUSCTRL_SIGN_CMD on one file, or skip when it is not set."""
    template = os.environ.get(SIGN_ENV, "").strip()
    if not template:
        print(f"  not signed ({SIGN_ENV} is not set)")
        return 0
    if "{file}" not in template:
        print(f"{SIGN_ENV} must contain {{file}} where the path goes.")
        return 1
    print(f"  signing {os.path.basename(path)}...")
    return subprocess.run(template.replace("{file}", f'"{path}"'), shell=True).returncode


def check_cryptography() -> str | None:
    """Return an error message unless cryptography imports and works.

    webbridge imports it lazily, only when the browser client mints its
    certificate. PyInstaller follows that import if the package is installed
    and silently leaves it out if it is not, so without this check a build
    from a machine missing it ships a --web mode that fails on the user's PC
    with no way to recover: a frozen app cannot pip install anything.
    """
    try:
        from cryptography import x509  # noqa: F401
        from cryptography.hazmat.primitives.asymmetric import rsa
        rsa.generate_private_key(public_exponent=65537, key_size=2048)
    except Exception as exc:  # ImportError, or a broken native binding
        return (
            f"cryptography is required, and the browser client disappears "
            f"from the build without it ({exc.__class__.__name__}: {exc}).\n"
            "  python -m pip install -r pc/requirements-build.txt"
        )
    return None


def main() -> int:
    onefile = "--onefile" in sys.argv
    console = "--console" in sys.argv

    if sys.platform != "win32":
        return print("The receiver is Windows only.") or 1

    try:
        import PyInstaller  # noqa: F401
    except ImportError:
        return print("PyInstaller is required:\n"
                     "  python -m pip install -r pc/requirements-build.txt") or 1

    try:
        import vgamepad
    except ImportError:
        return print("vgamepad is required:\n  python pc/install_vgamepad.py") or 1

    arch = "x64" if platform.architecture()[0] == "64bit" else "x86"
    pkg = os.path.dirname(vgamepad.__file__)
    dll = os.path.join(pkg, "win", "vigem", "client", arch, "ViGEmClient.dll")
    if not os.path.isfile(dll):
        return print(f"ViGEmClient.dll not found at {dll}") or 1

    icon = os.path.join(PC, "icon.ico")
    if not os.path.isfile(icon):
        make_icon = os.path.join(ROOT, "tools", "make_icon.py")
        if not os.path.isfile(make_icon):
            return print(f"{icon} is missing") or 1
        print("icon.ico missing, generating it first...")
        subprocess.run([sys.executable, make_icon], check=True)

    entry = "dualsense_link.py" if console else "app.py"

    if not console:
        try:
            import webview  # noqa: F401
        except ImportError:
            print("pywebview is required for the desktop app:")
            print("  python -m pip install -r pc/requirements-build.txt")
            return 1
        # The desktop app is the one with the browser client (--web).
        problem = check_cryptography()
        if problem:
            print(problem)
            return 1

    version = app_version()
    version_dir = tempfile.mkdtemp(prefix="ludusctrl-version-")
    version_file = write_version_file(version, version_dir)

    args = [
        sys.executable, "-m", "PyInstaller",
        "--onefile" if onefile else "--onedir",
        # The UI build is windowed: a console flashing behind a GUI looks
        # broken, and the app surfaces its own errors in the log panel.
        "--console" if console else "--windowed",
        "--clean",
        "--noconfirm",
        "--name", NAME,
        "--icon", os.path.abspath(icon),
        # Properties -> Details: version, product and copyright, from version.py.
        "--version-file", version_file,
        "--distpath", DIST,
        "--workpath", WORK,
        "--specpath", WORK,
        # Mirror vgamepad's own layout so its Path(__file__) lookup resolves.
        "--add-data", f"{dll};vgamepad/win/vigem/client/{arch}",
        # The app shows the icon in its own title bar too, so ship it inside.
        "--add-data", f"{os.path.abspath(icon)};.",
    ]

    # PyInstaller bundles anything importable that it can reach, which pulls in
    # roughly 25 MB nothing here uses:
    #
    #   tkinter/tcl/tk  the UI was Tk before WebView2 replaced it; nothing
    #                   imports it now
    #   gevent          not a pywebview dependency at all, just installed
    #                   in the same environment
    #
    # pywebview itself needs only bottle, proxy_tools, pythonnet and
    # typing_extensions, all of which stay.
    # cryptography is deliberately NOT excluded any more: webbridge needs it to
    # mint the self-signed certificate the browser client is served over, and a
    # frozen build cannot fall back to `pip install`. It is only imported on
    # first run, and only when --web is used, but it has to be present, which
    # is why check_cryptography() refuses to build without it.
    #
    # setuptools, wheel and packaging currently ride along too, reached through
    # cffi's build-time helpers. Nothing uses them at runtime, but they ship,
    # so THIRD-PARTY-NOTICES lists them. Excluding them is a separate change
    # that has to update that file in the same commit.
    for unused in ("tkinter", "_tkinter", "tcl", "tk", "Tkinter",
                   "gevent", "test", "unittest", "pydoc"):
        args += ["--exclude-module", unused]
    if not console:
        # Without these the WebView2 window loads nothing and shows an empty
        # background-coloured rectangle. Every front-end folder ships, so
        # `--ui <name>` works from the packaged exe and not just from source.
        for ui in UI_FOLDERS:
            src = os.path.join(PC, ui)
            if os.path.isdir(src):
                args += ["--add-data", f"{src};{ui}"]

    # Redistributing a build means shipping the bundled components' notices.
    notices = os.path.join(os.path.dirname(PC), "THIRD-PARTY-NOTICES")
    if os.path.isfile(notices):
        args += ["--add-data", f"{notices};."]
    args += [os.path.join(PC, entry)]

    mode = "onefile" if onefile else "onedir"
    kind = "console" if console else "desktop app"
    print(f"Building {NAME}.exe {version} ({arch}, {mode}, {kind})...\n")
    try:
        result = subprocess.run(args)
    finally:
        shutil.rmtree(version_dir, ignore_errors=True)
    if result.returncode != 0:
        return result.returncode

    exe = (os.path.join(DIST, NAME + ".exe") if onefile
           else os.path.join(DIST, NAME, NAME + ".exe"))
    if not os.path.isfile(exe):
        return print(f"PyInstaller reported success but {exe} is missing.") or 1

    if onefile:
        size = os.path.getsize(exe) / (1024 * 1024)
        note = ""
    else:
        size = sum(
            os.path.getsize(os.path.join(root, f))
            for root, _, files in os.walk(os.path.join(DIST, NAME))
            for f in files
        ) / (1024 * 1024)
        note = "  (whole folder - keep it together)"

    print(f"\n  {exe}")
    print(f"  {size:.1f} MB{note}")

    # The spec/work tree is large and fully derived; nothing needs it after this.
    shutil.rmtree(WORK, ignore_errors=True)

    # Signed last, so nothing rewrites the exe after the signature is applied.
    return sign(exe)


if __name__ == "__main__":
    raise SystemExit(main())
